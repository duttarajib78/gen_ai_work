"""Structured (JSON-lines) logging.

Policy: log counts, durations, identifiers generated by the service (request ids, model version)
and error codes. Never log request payloads, clinical codes, or admission numbers.
"""

from __future__ import annotations

import json
import logging
import os
import sys
from datetime import datetime, timezone
from typing import Any

_RESERVED = set(logging.LogRecord("", 0, "", 0, "", (), None).__dict__) | {"message", "asctime"}


class JsonFormatter(logging.Formatter):
    def format(self, record: logging.LogRecord) -> str:
        payload: dict[str, Any] = {
            "ts": datetime.fromtimestamp(record.created, tz=timezone.utc).isoformat(timespec="milliseconds"),
            "level": record.levelname,
            "logger": record.name,
            "message": record.getMessage(),
        }
        for key, value in record.__dict__.items():
            if key not in _RESERVED and not key.startswith("_"):
                payload[key] = value
        if record.exc_info:
            payload["exception"] = self.formatException(record.exc_info)
        return json.dumps(payload, default=str, separators=(",", ":"))


def configure_logging(level: str | None = None) -> None:
    """Idempotently route the ``drg_audit`` logger tree to stdout as JSON lines."""
    root = logging.getLogger("drg_audit")
    resolved = (level or os.environ.get("DRG_AUDIT_LOG_LEVEL", "INFO")).upper()
    root.setLevel(getattr(logging, resolved, logging.INFO))
    if any(getattr(h, "_drg_audit", False) for h in root.handlers):
        return
    handler = logging.StreamHandler(sys.stdout)
    handler.setFormatter(JsonFormatter())
    handler._drg_audit = True  # type: ignore[attr-defined]
    root.addHandler(handler)
    root.propagate = False


def get_logger(name: str) -> logging.Logger:
    return logging.getLogger(name if name.startswith("drg_audit") else f"drg_audit.{name}")


def log_event(logger: logging.Logger, event: str, level: int = logging.INFO, **fields: Any) -> None:
    """Emit one structured event. ``fields`` must be non-sensitive scalars."""
    logger.log(level, event, extra={"event": event, **fields})
