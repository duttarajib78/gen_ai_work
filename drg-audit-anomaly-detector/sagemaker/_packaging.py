"""Packaging helpers shared by the model-package and training-source builders (stdlib only)."""

from __future__ import annotations

import ast
import gzip
import hashlib
import shutil
import subprocess
import sys
import tarfile
from collections.abc import Sequence
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
SRC_PACKAGE = REPO_ROOT / "src" / "drg_audit"

# The endpoint ships only what it imports. Training, data, alerts, client and CLI code stay out of the
# serving package: smaller attack surface and no pandas / scikit-learn / boto3 requirement.
SERVING_MODULES = ("__init__.py", "_mapping.py", "artifacts.py", "errors.py", "features.py",
                   "logging_utils.py", "schemas.py", "settings.py")
SERVING_PACKAGES = ("inference", "models", "serving")
DEFAULT_PLATFORMS = ("manylinux2014_x86_64", "manylinux_2_17_x86_64", "manylinux_2_28_x86_64")
_IGNORE = shutil.ignore_patterns("__pycache__", "*.pyc", "*.pyo")


def sha256_file(path: Path, chunk_size: int = 1 << 20) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(chunk_size), b""):
            digest.update(chunk)
    return digest.hexdigest()


def copy_package(code_dir: Path, *, serving_only: bool) -> None:
    """Copy ``drg_audit`` into ``code_dir`` (whitelist for serving, everything for training)."""
    target = code_dir / "drg_audit"
    if not serving_only:
        shutil.copytree(SRC_PACKAGE, target, ignore=_IGNORE)
        return
    target.mkdir(parents=True)
    for module in SERVING_MODULES:
        shutil.copy2(SRC_PACKAGE / module, target / module)
    for package in SERVING_PACKAGES:
        shutil.copytree(SRC_PACKAGE / package, target / package, ignore=_IGNORE)


def read_requirements(path: Path) -> list[str]:
    """Flatten a requirements ``.in`` file: follows ``-r`` includes, drops comments and duplicates."""
    lines: list[str] = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split(" #")[0].strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith(("-r ", "--requirement ")):
            lines.extend(read_requirements((path.parent / line.split(None, 1)[1]).resolve()))
        elif line.startswith("-"):
            raise ValueError(f"unsupported option in {path.name}: {line.split()[0]}")
        else:
            lines.append(line)
    return list(dict.fromkeys(lines))


def vendor_wheels(
    requirements: Path, wheelhouse: Path, *, python_version: str, platforms: Sequence[str] = DEFAULT_PLATFORMS
) -> list[dict[str, Any]]:
    """Download wheels (binary only, resolved for the container's platform) into ``wheelhouse``."""
    wheelhouse.mkdir(parents=True, exist_ok=True)
    cmd = [sys.executable, "-m", "pip", "download", "--disable-pip-version-check", "--only-binary=:all:",
           "--dest", str(wheelhouse), "--python-version", python_version, "--implementation", "cp",
           "--abi", "cp" + python_version.replace(".", "")]
    for platform in platforms:
        cmd += ["--platform", platform]
    cmd += ["-r", str(requirements)]
    subprocess.run(cmd, check=True)  # noqa: S603  (fixed argv, no shell)
    files = sorted(wheelhouse.iterdir())
    if not files or any(f.suffix != ".whl" for f in files):
        raise RuntimeError("the wheelhouse must contain wheel files only")
    return [{"file": f.name, "sha256": sha256_file(f), "bytes": f.stat().st_size} for f in files]


def write_requirements(path: Path, lines: Sequence[str], *, find_links: str | None) -> None:
    out = ["# Generated by the packaging tooling; do not edit."]
    if find_links is not None:
        out += ["--no-index", f"--find-links={find_links}"]
    out += list(lines)
    path.write_text("\n".join(out) + "\n", encoding="utf-8")


def assert_import_closure(code_dir: Path, package: str = "drg_audit") -> None:
    """Fail the build if any ``drg_audit`` import in the staged code cannot be resolved inside it."""
    missing: set[str] = set()
    for source in code_dir.rglob("*.py"):
        relative = source.relative_to(code_dir)
        if "wheelhouse" in relative.parts:
            continue
        for node in ast.walk(ast.parse(source.read_text(encoding="utf-8"), filename=str(source))):
            modules: list[str] = []
            if isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
                modules.append(node.module)
            elif isinstance(node, ast.Import):
                modules.extend(alias.name for alias in node.names)
            for module in modules:
                if module != package and not module.startswith(package + "."):
                    continue
                base = code_dir / Path(*module.split("."))
                if not (base.with_suffix(".py").is_file() or (base / "__init__.py").is_file()):
                    missing.add(f"{relative.as_posix()} -> {module}")
    if missing:
        raise RuntimeError("staged code imports modules that were not packaged: " + ", ".join(sorted(missing)))


def _normalise(info: tarfile.TarInfo) -> tarfile.TarInfo:
    info.uid = info.gid = 0
    info.uname = info.gname = ""
    info.mtime = 0
    info.mode = 0o755 if info.isdir() else 0o644
    return info


def write_deterministic_targz(source_dir: Path, output: Path) -> str:
    """Reproducible tar.gz (sorted members, zeroed owners and timestamps, no gzip mtime). Returns SHA-256."""
    output.parent.mkdir(parents=True, exist_ok=True)
    with open(output, "wb") as raw, gzip.GzipFile(filename="", mode="wb", fileobj=raw, compresslevel=6,
                                                   mtime=0) as gz, tarfile.open(fileobj=gz, mode="w",
                                                                                 format=tarfile.GNU_FORMAT) as tar:
        for path in sorted(source_dir.rglob("*")):
            tar.add(path, arcname=path.relative_to(source_dir).as_posix(), recursive=False, filter=_normalise)
    return sha256_file(output)
